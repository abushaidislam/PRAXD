import { ReviewContext } from "./context-builder";
import { AIReviewResult } from "@/types/ai-review";
import { AIReviewProvider, SYSTEM_PROMPT } from "./reviewer";
import { validateAiReviewOutput } from "./validator";
import { parseJsonSafe } from "./anthropic-reviewer";
import { SelfHostedConfig } from "@/types/governance";

const FORBIDDEN_HEADERS = new Set([
  "host",
  "content-length",
  "connection",
  "transfer-encoding",
  "upgrade",
  "keep-alive",
  "proxy-connection",
]);

/**
 * Validates endpoint URL and TLS protocol.
 */
export function validateSelfHostedEndpoint(baseUrl: string, requireTls: boolean = true): URL {
  let parsedUrl: URL;
  try {
    parsedUrl = new URL(baseUrl);
  } catch {
    throw new Error(`Invalid self-hosted endpoint URL: '${baseUrl}'`);
  }

  if (requireTls && parsedUrl.protocol !== "https:") {
    throw new Error(
      `Insecure self-hosted endpoint: TLS is required for enterprise compliance (expected 'https://', received '${parsedUrl.protocol}')`
    );
  }

  return parsedUrl;
}

/**
 * Validates and filters custom headers to prevent HTTP header injection or hop-by-hop tampering.
 */
export function sanitizeCustomHeaders(headers?: Record<string, string>): Record<string, string> {
  if (!headers) return {};

  const sanitized: Record<string, string> = {};
  for (const [key, val] of Object.entries(headers)) {
    const lowerKey = key.trim().toLowerCase();

    // Block dangerous headers
    if (FORBIDDEN_HEADERS.has(lowerKey)) {
      continue;
    }

    // Validate against header injection characters (CRLF)
    if (/[\r\n]/.test(key) || /[\r\n]/.test(val)) {
      throw new Error(`Invalid header contains CRLF injection attempt: '${key}'`);
    }

    sanitized[key.trim()] = val.trim();
  }

  return sanitized;
}

/**
 * Enterprise Self-Hosted Reviewer (Ollama, vLLM, Azure OpenAI, LocalAI).
 * Communicates with any OpenAI-compatible /v1/chat/completions endpoint.
 */
export class SelfHostedReviewer implements AIReviewProvider {
  private config: SelfHostedConfig;

  constructor(config: SelfHostedConfig) {
    this.config = config;
    // Validate on construction
    validateSelfHostedEndpoint(config.baseUrl, config.requireTls ?? true);
  }

  async executeReview(context: ReviewContext): Promise<AIReviewResult> {
    const parsedUrl = validateSelfHostedEndpoint(
      this.config.baseUrl,
      this.config.requireTls ?? true
    );

    // Normalize endpoint path: ensure /v1/chat/completions or /chat/completions
    let endpoint = parsedUrl.toString().replace(/\/+$/, "");
    if (!endpoint.endsWith("/chat/completions")) {
      if (endpoint.endsWith("/v1")) {
        endpoint += "/chat/completions";
      } else {
        endpoint += "/v1/chat/completions";
      }
    }

    const safeHeaders = sanitizeCustomHeaders(this.config.customHeaders);

    const headers: Record<string, string> = {
      "Content-Type": "application/json",
      ...safeHeaders,
    };

    if (this.config.apiKey) {
      headers["Authorization"] = `Bearer ${this.config.apiKey}`;
    }

    const userPrompt = `Review pull request #${context.pullRequest.number}: "${context.pullRequest.title}".
Head SHA: ${context.pullRequest.headSha}
Repository: ${context.repository.fullName}

Changed files:
${JSON.stringify(context.changedFiles, null, 2)}`;

    const model = this.config.model || "default-model";

    const response = await fetch(endpoint, {
      method: "POST",
      headers,
      body: JSON.stringify({
        model,
        temperature: 0.1,
        messages: [
          { role: "system", content: SYSTEM_PROMPT },
          { role: "user", content: userPrompt },
        ],
      }),
    });

    if (!response.ok) {
      const err = await response.text().catch(() => "");
      throw new Error(`Self-hosted inference endpoint error (${response.status}): ${err}`);
    }

    const json = await response.json();
    const content = json.choices?.[0]?.message?.content;
    if (!content) {
      throw new Error("No completion generated by self-hosted inference model.");
    }

    const parsed = parseJsonSafe(content);
    const validation = validateAiReviewOutput(parsed, context);
    if (!validation.isValid) {
      throw new Error(`AI Review validation failed: ${validation.errorMessage}`);
    }

    return validation.result;
  }
}
