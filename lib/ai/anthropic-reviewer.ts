import { ReviewContext } from "./context-builder";
import { AIReviewResult } from "@/types/ai-review";
import { AIReviewProvider, SYSTEM_PROMPT } from "./reviewer";
import { validateAiReviewOutput } from "./validator";

export function parseJsonSafe(rawContent: string): any {
  if (!rawContent) throw new Error("Empty model response.");
  let cleaned = rawContent.trim();
  if (cleaned.startsWith("```")) {
    cleaned = cleaned.replace(/^```(?:json)?\s*/i, "").replace(/\s*```$/, "").trim();
  }
  return JSON.parse(cleaned);
}

/**
 * Anthropic Claude Reviewer (Claude 3.7 Sonnet / 3.5 Haiku)
 * Supports Zero-Data-Retention (ZDR) contract headers.
 */
export class AnthropicReviewer implements AIReviewProvider {
  private apiKey: string;
  private model: string;
  private zeroDataRetention: boolean;

  constructor(apiKey: string, model?: string, zeroDataRetention: boolean = false) {
    this.apiKey = apiKey;
    this.model = model || process.env.ANTHROPIC_MODEL || "claude-3-7-sonnet-20250219";
    this.zeroDataRetention = zeroDataRetention;
  }

  async executeReview(context: ReviewContext): Promise<AIReviewResult> {
    const userPrompt = `Review pull request #${context.pullRequest.number}: "${context.pullRequest.title}".
Head SHA: ${context.pullRequest.headSha}
Repository: ${context.repository.fullName}

Changed files:
${JSON.stringify(context.changedFiles, null, 2)}`;

    const headers: Record<string, string> = {
      "x-api-key": this.apiKey,
      "anthropic-version": "2023-06-01",
      "content-type": "application/json",
    };

    if (this.zeroDataRetention) {
      headers["anthropic-beta"] = "zero-data-retention";
    }

    const response = await fetch("https://api.anthropic.com/v1/messages", {
      method: "POST",
      headers,
      body: JSON.stringify({
        model: this.model,
        max_tokens: 4096,
        system: SYSTEM_PROMPT,
        messages: [{ role: "user", content: userPrompt }],
      }),
    });

    if (!response.ok) {
      const err = await response.text();
      throw new Error(`Anthropic API error (${response.status}): ${err}`);
    }

    const json = await response.json();
    const content = json.content?.[0]?.text;
    if (!content) {
      throw new Error("No text response generated by Anthropic Claude model.");
    }

    const parsed = parseJsonSafe(content);
    const validation = validateAiReviewOutput(parsed, context);
    if (!validation.isValid) {
      throw new Error(`AI Review validation failed: ${validation.errorMessage}`);
    }

    return validation.result;
  }
}
